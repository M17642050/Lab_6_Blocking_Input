import java.util.Scanner;
import java.util.Random;
public class HighorLow {
    public static void main (String [] args) {
        Scanner in = new Scanner(System.in);
        Random rnd = new Random();
        int usrG = 0;
        boolean loop = true;
        int rnd2 = rnd.nextInt(10) + 1;
        do {
            System.out.print("Enter an integer between, and including, 1 and 10: ");
            if (in.hasNextInt()) {
                usrG = in.nextInt();
                in.nextLine();
                if (usrG > 0 && usrG < 11) {
                    if (usrG == rnd2) {
                        System.out.println("Your guess of " + usrG + " matches the number generated by the random number generator.");
                        loop = false;
                    }
                    else {
                        System.out.println("Your guess of " + usrG + " does not match the number generated by the random number generator. Here, try again:");
                        rnd2 = rnd.nextInt(10) + 1;
                    }
                }
                else {
                    System.out.println("Out of range. " + usrG + " is not 1, 10, or between 1 and 10.");
                }
            }
            else {
                String trash = in.nextLine();
                System.out.println("Invalid Input. Please enter an integer between, and including, 1 and 10.");
            }
        }
        while (loop);
    }
}